// Κανόνας κελύφους λεπτομέρειας — μέρος του `node scripts/check-design.mjs`.
//
// Μια οθόνη λεπτομέρειας έχει τρία πράγματα που τα ξαναγράφει ο καθένας από την
// αρχή: σύνδεσμο επιστροφής, τίτλο, και (καμιά φορά) καρτέλες. Το
// `src/components/shared/detail-shell.tsx` τα κατέχει και τα τρία, ΚΑΙ παίρνει
// μια απόφαση που κανένα χειροποίητο κέλυφος δεν παίρνει μόνο του: ο σύνδεσμος
// επιστροφής στέκεται ΠΑΝΩ από τον τίτλο, όχι μέσα στις ενέργειες — η πλοήγηση
// δεν κάθεται δίπλα στη διαγραφή. Κάθε οθόνη που το γράφει στο χέρι ξαναπαίρνει
// αυτή την απόφαση σιωπηλά, και συνήθως ανάποδα.
//
// ΕΜΒΕΛΕΙΑ: μόνο `src/app/**/[param]/**`. Το δυναμικό τμήμα διαδρομής ΕΙΝΑΙ ο
// ορισμός της «οθόνης λεπτομέρειας» — δείχνει ένα συγκεκριμένο αντικείμενο, άρα
// υπάρχει και κάτι από το οποίο ήρθες. Οι στατικές διαδρομές (σύνδεση, δημόσια
// κράτηση, κόμβοι) μένουν έξω ΕΞ ΟΡΙΣΜΟΥ, όχι με εγγραφή σε λίστα — γι' αυτό
// δεν θα βρεις εδώ εξαίρεση για τις σελίδες αυθεντικοποίησης.

const DETAIL_ROUTE = /\/\[[^/\]]+\]\//;

const SHELL_IMPORT = /from\s+['"](?:@\/components\/shared\/detail-shell|\.[^'"]*\/detail-shell)['"]/;

// Πότε ένα αρχείο μέσα σε δυναμική διαδρομή είναι ΟΘΟΝΗ και όχι περιτύλιγμα.
// Τα `page.tsx`/`loading.tsx` που απλώς φορτώνουν δεδομένα και δίνουν τη σκυτάλη
// δεν γράφουν τίτλο ούτε επιστροφή, άρα πέφτουν έξω μόνα τους — δεν χρειάζεται
// να τα εξαιρέσουμε ονομαστικά, και καλά κάνει: ένα `page.tsx` ΜΠΟΡΕΙ να είναι
// ολόκληρη οθόνη (η επεξεργασία πελάτη είναι ακριβώς αυτό) και τότε το θέλουμε
// μέσα.
const OWN_HEADING = /<h1\b/;

// ΓΝΩΣΤΟ ΟΡΙΟ, γραμμένο αντί για υπονοούμενο: ο ανιχνευτής βλέπει τον σύνδεσμο
// επιστροφής από το ΕΙΚΟΝΙΔΙΟ ή από την ΕΤΙΚΕΤΑ του. Μια οθόνη λεπτομέρειας που
// γράφει δικό της `PageHeading` ΧΩΡΙΣ καθόλου επιστροφή δεν πιάνεται — και δεν
// θέλουμε να πιαστεί από το σκέτο `PageHeading`, γιατί τότε ο κανόνας θα
// κατήγγειλλε κάθε φόρμα και κάθε λίστα κάτω από δυναμικό τμήμα. Κλείνει προς
// τα μέσα όσο μπορεί να αποδείξει, και σταματά εκεί.
// Η ετικέτα μετράει εξίσου με το εικονίδιο: ένα `tc('back')` σε `<Button asChild>`
// είναι ο ίδιος σύνδεσμος επιστροφής χωρίς `ArrowLeft` — και οι δύο σελίδες
// επιστροφής του Stripe έτσι είναι γραμμένες.
const BACK_LINK = /\bArrowLeft\b|\bChevronLeft\b|\bbackHref\b|\bt[A-Za-z]*\(['"]back[A-Za-z]*['"]\)/;

// Οθόνες που ΔΕΝ πρόκειται ποτέ να φορέσουν το κέλυφος — όχι «δεν πρόλαβαν».
//
// Ruling I — η σελίδα επιστροφής μιας πληρωμής δεν είναι οθόνη λεπτομέρειας.
// Δεν δείχνει το τιμολόγιο· δείχνει την ΕΚΒΑΣΗ μιας συναλλαγής που μόλις έγινε
// αλλού (Stripe) και σε ξαναέφερε πίσω: μία κεντραρισμένη κάρτα, χωρίς τίτλο
// σελίδας, χωρίς καρτέλες, με δύο κουμπιά που είναι η ΣΥΝΕΧΕΙΑ και όχι
// «επιστροφή» — «δοκίμασε ξανά», «στα τιμολόγιά μου». Ένα `DetailShell` εδώ θα
// πρόσθετε τίτλο και μπάρα επιστροφής πάνω από μια κάρτα που ολόκληρος ο λόγος
// ύπαρξής της είναι να μη μοιάζει με σελίδα του προϊόντος. Ίδια κλάση με το
// Ruling E: το σχήμα δεν ταιριάζει και δεν πρόκειται να ταιριάξει.
const DETAIL_SHELL_EXEMPT = [
  'src/app/client/invoices/[invoiceId]/cancel/page.tsx',
  'src/app/client/invoices/[invoiceId]/success/success-content.tsx',
];

// Οθόνες λεπτομέρειας που ΔΕΝ έχουν μεταναστεύσει ακόμα, με ρητό λόγο. Η λίστα
// μόνο μικραίνει, και ο αριθμός στο τέλος τις αφαιρεί — αλλιώς ο φύλακας
// διαφημίζει κάλυψη που δεν έχει.
//
// Άδεια σήμερα: και οι τρεις οθόνες που κρατούσαν εγγραφή εδώ (φόρμα
// επεξεργασίας πελάτη, φόρμα επεξεργασίας υποψήφιου πελάτη, προεπισκόπηση
// άρθρου) φορούν πλέον το `DetailShell`.
const DETAIL_SHELL_PENDING = [];

const normalise = (p) => p.replaceAll('\\', '/');

export function checkDetailShell({ files, strippedOf }) {
  const inScope = files.filter(
    (f) => f.startsWith('src/app/') && !f.startsWith('src/app/api/') && DETAIL_ROUTE.test(f),
  );

  // Οθόνη μέσα σε δυναμική διαδρομή που ΔΕΝ φοράει το κέλυφος, με το σημάδι που
  // την πρόδωσε — ώστε το μήνυμα να λέει τι είδε ο ανιχνευτής, όχι μόνο ότι
  // είδε κάτι.
  const bare = new Map();
  for (const file of inScope) {
    const source = strippedOf(file);
    if (SHELL_IMPORT.test(source)) continue;
    if (OWN_HEADING.test(source)) bare.set(file, 'writes its own <h1>');
    else if (BACK_LINK.test(source)) bare.set(file, 'writes its own back link');
  }

  const exempt = new Set(DETAIL_SHELL_EXEMPT.map(normalise));
  const pending = new Set(DETAIL_SHELL_PENDING.map(normalise));

  const violations = [];
  for (const [file, why] of bare) {
    if (exempt.has(file) || pending.has(file)) continue;
    violations.push(`${file}\n      ${why}, outside the shared DetailShell`);
  }

  // Ίδιος έλεγχος και για τις δύο λίστες, ίδιος λόγος: μια εγγραφή που φόρεσε
  // το κέλυφος, έπαψε να είναι οθόνη, ή εξαφανίστηκε, δεν φυλάει πια τίποτα —
  // κάθεται σιωπηλή δίνοντας την εντύπωση ότι φυλάει.
  const stale = [];
  for (const entry of [...pending, ...exempt]) {
    if (!bare.has(entry)) stale.push(entry);
  }

  return {
    violations,
    stale,
    counts: { checked: inScope.length - pending.size - exempt.size, pending: pending.size, exempt: exempt.size },
  };
}
